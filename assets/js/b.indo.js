  // Helper to compile basic markdown tags to styled HTML
  function compileMarkdownToHtml(markdown, isSerif = true) {
    if (!markdown) return '';

    // Format headings (H4 with colored left border)
    let html = markdown.replace(/^### (.*$)/gim, `<h4 class="text-base sm:text-lg font-extrabold text-zinc-900 dark:text-white mt-6 mb-3 border-l-4 border-pink-500 pl-3 font-${isSerif ? 'serif' : 'sans'}">$1</h4>`);

    // Format subheadings (H3)
    html = html.replace(/^## (.*$)/gim, `<h3 class="text-lg sm:text-xl font-extrabold text-zinc-955 dark:text-white mt-8 mb-4 font-${isSerif ? 'serif' : 'sans'}">$1</h3>`);

    // Format bold text
    html = html.replace(/\*\*(.*?)\*\*/g, '<strong class="font-extrabold text-zinc-900 dark:text-white">$1</strong>');

    // Format bullet items
    html = html.replace(/^\- (.*$)/gim, '<li class="ml-5 list-disc pl-1 text-zinc-750 dark:text-zinc-350 leading-relaxed">$1</li>');

    // Format horizontal rules
    html = html.replace(/^---$/gim, '<div class="border-t border-double border-pink-200/60 dark:border-zinc-800/60 my-6"></div>');

    // Split content by paragraphs and wrap plain lines in p tags
    const lines = html.split('\n');
    let insideList = false;
    const processedLines = lines.map(line => {
      const trimmed = line.trim();
      if (!trimmed) {
        if (insideList) {
          insideList = false;
          return '</ul>';
        }
        return '';
      }

      if (trimmed.startsWith('<h') || trimmed.startsWith('<div') || trimmed.startsWith('<hr')) {
        if (insideList) {
          insideList = false;
          return '</ul>' + trimmed;
        }
        return trimmed;
      }

      if (trimmed.startsWith('<li')) {
        if (!insideList) {
          insideList = true;
          return '<ul class="space-y-1 mb-4">' + trimmed;
        }
        return trimmed;
      }

      // Normal paragraph
      if (insideList) {
        insideList = false;
        return '</ul>' + `<p class="mb-4 leading-relaxed text-justify">${trimmed}</p>`;
      }

      return `<p class="mb-4 leading-relaxed text-justify">${trimmed}</p>`;
    });

    if (insideList) {
      processedLines.push('</ul>');
    }

    let result = processedLines.join('');
    if (isSerif) {
      result = result.replace('<p class="mb-4 leading-relaxed text-justify">', '<p class="mb-4 leading-relaxed text-justify drop-cap-premium">');
    }
    return result;
  }

